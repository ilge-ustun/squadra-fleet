import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { runSync } from './proc.ts';
import { formatIsoSeconds, parseMutRows, parseProbeRows, renderRoundSection, splitWords } from './machine-block.ts';
import { computeVerdict } from './verdict.ts';
import { isColour, isVerdict, type Baseline } from './types.ts';

const FIXTURES = resolve(import.meta.dirname, '../../fixtures/verdict');

/** The goldens: for each <name>.input.json (what bash hands over) the bytes
 *  bash wrote for it, <name>.expected.md — generated by gen.sh from the
 *  retired verdict block and heredoc. The rule and the renderer are checked
 *  together, as bash ran them together. */
describe('renderRoundSection — byte for byte against the bash heredoc', () => {
  const names = readdirSync(FIXTURES).filter((f) => f.endsWith('.input.json')).map((f) => f.replace(/\.input\.json$/, ''));
  it('has the five variants', () => {
    expect(names.sort()).toEqual(['both', 'mutations', 'no-tables', 'probes', 'spec']);
  });
  it.each(names)('%s', (name) => {
    const raw = JSON.parse(readFileSync(join(FIXTURES, `${name}.input.json`), 'utf8')) as Record<string, string | Record<string, string>>;
    const str = (k: string): string => raw[k] as string;
    const obj = (k: string): Record<string, string> => raw[k] as Record<string, string>;
    const [bt, bb, bl] = [obj('baseline')['test'] ?? '', obj('baseline')['build'] ?? '', obj('baseline')['lint'] ?? ''];
    if (!isColour(bt) || !isColour(bb) || !isColour(bl)) throw new Error('fixture baseline');
    const baseline: Baseline = { test: bt, build: bb, lint: bl };
    const mutRows = parseMutRows(str('mutRows'));
    const probeRows = parseProbeRows(str('probeRows'));
    const acIds = splitWords(str('acs'));
    const scopeHits = splitWords(str('scopeHits'));
    const v = computeVerdict({ baseline, scope: str('scope'), scopeHits, acIds, mutRows, probeRows, reviewerText: str('reviewerText') });
    const timing = obj('timing');
    const out = renderRoundSection({
      round: str('round'), headSha: str('headSha'), roundCommits: str('roundCommits'), reviewedAt: str('reviewedAt'),
      baseline,
      timing: { build: timing['build'] ?? '', base: timing['base'] ?? '', review: timing['review'] ?? '', mut: timing['mut'] ?? '', total: timing['total'] ?? '' },
      builderModel: str('builderModel'), reviewerModel: str('reviewerModel'),
      acIds, scope: str('scope'), scopeHits,
      model: v.model, computed: v.computed, reasons: v.reasons, mutRows, probeRows,
      // launch.sh:662-663 wrote each file as the variable plus one newline
      builderText: Buffer.from(`${str('builderMsg')}\n`, 'utf8'),
      reviewerText: Buffer.from(`${str('reviewerText')}\n`, 'utf8'),
    });
    const expected = readFileSync(join(FIXTURES, `${name}.expected.md`));
    expect(out.toString('utf8')).toBe(expected.toString('utf8'));
    expect(Buffer.compare(out, expected)).toBe(0);
    expect(isVerdict(v.computed)).toBe(true);
  });
});

describe('the row parsers — awk $1 $2 $3 and `read -r ac cls slug` agree on these', () => {
  it('parseMutRows', () => {
    expect(parseMutRows('AC1 RED marker\n\nAC2 NO_SELECTOR bad\n')).toEqual([
      { ac: 'AC1', cls: 'RED', slug: 'marker' }, { ac: 'AC2', cls: 'NO_SELECTOR', slug: 'bad' },
    ]);
    expect(parseMutRows('AC1  slug-only')).toEqual([{ ac: 'AC1', cls: 'slug-only', slug: '' }]);
    expect(parseMutRows('AC1')).toEqual([{ ac: 'AC1', cls: '', slug: '' }]);
    expect(parseMutRows('AC1 GREEN my slug ')).toEqual([{ ac: 'AC1', cls: 'GREEN', slug: 'my slug' }]);
    expect(parseMutRows('   \n')).toEqual([]);
  });
  it('a slug with whitespace: the table shows its first word (awk $3), the reason the whole (read -r)', () => {
    const rows = parseMutRows('AC1 GREEN my slug');
    const v = computeVerdict({ baseline: { test: 'GREEN', build: 'GREEN', lint: 'GREEN' }, scope: 'CLEAN', scopeHits: [], acIds: ['AC1'], mutRows: rows, probeRows: [], reviewerText: 'VERDICT: PASS' });
    expect(v.reasons).toEqual(['AC1 my slug GREEN']);
    const out = renderRoundSection({
      round: '1', headSha: 'h', roundCommits: '1', reviewedAt: 't', baseline: { test: 'GREEN', build: 'GREEN', lint: 'GREEN' },
      timing: { build: '0', base: '0', review: '0', mut: '0', total: '0' }, builderModel: 'm', reviewerModel: '',
      acIds: ['AC1'], scope: 'CLEAN', scopeHits: [], model: 'PASS', computed: 'FAIL', reasons: v.reasons, mutRows: rows, probeRows: [],
      builderText: Buffer.from('b\n'), reviewerText: Buffer.from('r\n'),
    }).toString('utf8');
    expect(out).toContain('\nAC1  GREEN         my\n');
  });
  it('parseProbeRows, including the empty class the unchecked runner used to leave', () => {
    expect(parseProbeRows('probe-green.test.tsx GREEN\nprobe-red.test.tsx RED\n')).toEqual([
      { name: 'probe-green.test.tsx', cls: 'GREEN' }, { name: 'probe-red.test.tsx', cls: 'RED' },
    ]);
    expect(parseProbeRows('probe-green.test.tsx \n')).toEqual([{ name: 'probe-green.test.tsx', cls: '' }]);
  });
  it('splitWords', () => {
    expect(splitWords('AC1 AC2 ')).toEqual(['AC1', 'AC2']);
    expect(splitWords('AC1 ')).toEqual(['AC1']);
    expect(splitWords('')).toEqual([]);
  });
});

describe('formatIsoSeconds — date -Iseconds', () => {
  const epoch = 1758621600; // 2026-09-23T10:00:00Z
  it.each(['Europe/Rome', 'UTC', 'Asia/Kolkata', 'America/New_York'])('under TZ=%s', (tz) => {
    const before = process.env['TZ'];
    try {
      process.env['TZ'] = tz;                           // Node re-reads TZ on assignment
      const fromDate = runSync('bash', ['-c', `TZ=${tz} date -Iseconds -d @${epoch}`]).stdout.trim();
      expect(formatIsoSeconds(new Date(epoch * 1000))).toBe(fromDate);
    } finally {
      if (before === undefined) delete process.env['TZ']; else process.env['TZ'] = before;
    }
  });
});
